namespace GensouGL.Audio;

/// <summary>
/// Represents audio playback states.
/// </summary>
public enum AudioState
{
    /// <summary>
    /// Audio is playing.
    /// </summary>
    Playing,
    /// <summary>
    /// Audio is paused.
    /// </summary>
    Paused,
    /// <summary>
    /// Audio is stopped.
    /// </summary>
    Stopped
}